#!/usr/bin/env python3
"""
kappa_EB_test.py — IS THE KAPPA FIELD AN INTERFERENCE PATTERN, OR IS IT NOISE?

Cody's expectation: the convergence should look like "a handful of gravel thrown
into a still pond" -- 2D surface-wave interference. That is the LCDRM / wave-DM
prediction, and the README's Deltakappa fringe test.

The problem: smoothed shape noise ALSO looks like a field of alternating
positive/negative blobs. The two are visually identical. So use the null that
weak lensing already provides:

    GRAVITATIONAL LENSING PRODUCES E-MODE ONLY.
    B-mode is generated by NO physical lensing signal -- it is systematics + noise.

Kaiser-Squires on shear rotated by 45 degrees (g1,g2) -> (-g2,g1) yields the
B-mode. Run BOTH through the SAME pipeline (same taper, same padding), then:

  1. amplitude    rms(E) vs rms(B)      equal -> noise dominated
  2. power spectrum P_E(k) vs P_B(k)    E excess at some k -> real structure at that scale
  3. characteristic scale vs the SMOOTHING KERNEL
     SMOOTH_PX=60 native, BIN=32 -> sigma = 1.875 coarse px.
     If the blob scale equals the kernel scale, the blobs ARE the kernel.

A real interference pattern has a PREFERRED WAVELENGTH -- a peak in P(k).
Smoothed noise has no peak; it just rolls off at the kernel scale.
"""
import sys, glob, os
import numpy as np

sys.path.insert(0, "/home/rendier/Projects/ThePlace/ValaQuenta/modules/l_io_photon_path")
from maths import bounded_lensing_pipeline

PIX  = "/home/rendier/Projects/ThePlace/BulletCluster/optical/jwst/prepped/pixel_field"
LIO  = "/home/rendier/Projects/ThePlace/BulletCluster/optical/jwst/prepped/l_io"
BIN  = 32
SMOOTH_PX = 60
PSCL_NATIVE = 1.929 / BIN          # arcsec per native px (validated earlier)
PSCL_COARSE = 1.929

def block_average(a, b):
    ny, nx = a.shape
    ny_c, nx_c = ny // b, nx // b
    a = a[:ny_c*b, :nx_c*b]
    return a.reshape(ny_c, b, nx_c, b).mean(axis=(1, 3))

E1 = np.load(f"{PIX}/E1_BG.npy"); E2 = np.load(f"{PIX}/E2_BG.npy")
g1 = block_average(E1, BIN); g2 = block_average(E2, BIN)
ny, nx = g1.shape
print(f"coarse shear grid : {nx} x {ny}  @ {PSCL_COARSE}\"/px")
print(f"smoothing kernel  : SMOOTH_PX={SMOOTH_PX} native = "
      f"{SMOOTH_PX/BIN:.3f} coarse px sigma  ({SMOOTH_PX*PSCL_NATIVE:.2f}\")")

# ── E-mode (as shipped) and B-mode (shear rotated 45 deg) ────────────────────
print("\nrunning pipeline: E-mode ...")
E = bounded_lensing_pipeline(g1, g2, PSCL_COARSE, taper_frac=0.1, pad_factor=2.0)
print("running pipeline: B-mode (45 deg rotated shear) ...")
B = bounded_lensing_pipeline(-g2, g1, PSCL_COARSE, taper_frac=0.1, pad_factor=2.0)
kE, kB = E['kappa'], B['kappa']

ref = np.load(f"{LIO}/kappa.npy")
print(f"\nreproduces shipped kappa.npy: max|diff| = {np.nanmax(np.abs(kE-ref)):.2e}")

# ── 1. amplitude ─────────────────────────────────────────────────────────────
print("\n" + "="*68)
print("1. AMPLITUDE  -- if rms(E) ~ rms(B), the map is noise dominated")
print("="*68)
rE, rB = np.nanstd(kE), np.nanstd(kB)
print(f"  rms(kappa_E) = {rE:.5f}")
print(f"  rms(kappa_B) = {rB:.5f}")
print(f"  ratio E/B    = {rE/rB:.3f}      (1.0 = pure noise, >>1 = real signal)")

# ── 2. power spectra ─────────────────────────────────────────────────────────
def radial_power(m):
    m = np.nan_to_num(m - np.nanmean(m))
    w = np.hanning(m.shape[0])[:, None] * np.hanning(m.shape[1])[None, :]
    F = np.fft.fftshift(np.fft.fft2(m * w))
    P = np.abs(F)**2
    cy, cx = np.array(P.shape) // 2
    y, x = np.indices(P.shape)
    r = np.sqrt((y-cy)**2 + (x-cx)**2).astype(int)
    nb = min(cy, cx)
    prof = np.array([P[r == i].mean() for i in range(1, nb)])
    return np.arange(1, nb), prof

k, PE = radial_power(kE)
_, PB = radial_power(kB)
lam = 2.0 * min(nx, ny) / k          # wavelength in coarse px

print("\n" + "="*68)
print("2. POWER SPECTRUM  -- a real interference pattern has a PEAK in P_E/P_B")
print("="*68)
print(f"  {'k':>4}{'lambda (px)':>13}{'lambda (\")':>12}{'P_E/P_B':>10}")
ratio = PE / np.maximum(PB, 1e-30)
for i in range(0, min(len(k), 22), 2):
    print(f"  {k[i]:>4}{lam[i]:>13.1f}{lam[i]*PSCL_COARSE:>12.1f}{ratio[i]:>10.3f}")
pk = int(np.argmax(ratio[:len(ratio)//2]))
print(f"\n  max E/B excess at k={k[pk]}  lambda={lam[pk]:.1f} px "
      f"= {lam[pk]*PSCL_COARSE:.1f}\"   ratio {ratio[pk]:.3f}")

# ── 3. characteristic scale vs the kernel ────────────────────────────────────
def corr_length(m):
    """1/e width of the radial autocorrelation, in coarse px."""
    m = np.nan_to_num(m - np.nanmean(m))
    F = np.fft.fft2(m)
    ac = np.fft.fftshift(np.real(np.fft.ifft2(F*np.conj(F))))
    ac /= ac.max()
    cy, cx = np.array(ac.shape)//2
    prof = ac[cy, cx:]
    below = np.where(prof < 1/np.e)[0]
    return float(below[0]) if len(below) else float(len(prof))

lE, lB = corr_length(kE), corr_length(kB)
kern = SMOOTH_PX / BIN
print("\n" + "="*68)
print("3. CHARACTERISTIC SCALE  -- is the blob size just the smoothing kernel?")
print("="*68)
print(f"  correlation length E : {lE:.2f} coarse px  ({lE*PSCL_COARSE:.1f}\")")
print(f"  correlation length B : {lB:.2f} coarse px  ({lB*PSCL_COARSE:.1f}\")")
print(f"  smoothing kernel sig : {kern:.2f} coarse px  ({kern*PSCL_COARSE:.1f}\")")

print("\n" + "="*68)
print("VERDICT")
print("="*68)
if rE/rB > 1.5 and ratio[pk] > 1.5:
    print(f"  E-mode exceeds B-mode AND shows a spectral peak at "
          f"{lam[pk]*PSCL_COARSE:.0f}\".")
    print("  -> consistent with real structure at a preferred scale.")
elif rE/rB < 1.25:
    print("  E and B are comparable in amplitude.")
    print("  -> the field is NOISE DOMINATED. Blob pattern is not evidence of")
    print("     interference; smoothed shape noise looks identical.")
else:
    print("  Marginal. E slightly exceeds B but with no clear spectral peak.")
    print("  -> cannot distinguish interference from noise with this footprint.")
